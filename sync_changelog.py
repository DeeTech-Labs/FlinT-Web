#!/usr/bin/env python3
"""Embed product changelogs. Use --fetch to refresh committed snapshots from GitHub."""
import argparse
import json
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parent
PRODUCTS = (("os", "FlinT-OS", "changelog.data.js"),
            ("desktop", "FlinT-Desktop", "desktop-changelog.data.js"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fetch', action='store_true')
    args = parser.parse_args()
    # Fetch every source successfully before replacing any snapshot.
    sources = {}
    for product, repo, output in PRODUCTS:
        snapshot = ROOT / 'changelogs' / f'{product}.md'
        if args.fetch:
            with urlopen(f'https://raw.githubusercontent.com/DeeTech-Labs/{repo}/main/CHANGELOG.md', timeout=30) as response:
                content = response.read().decode('utf-8')
            if not content.lstrip().startswith('#'):
                raise ValueError(f'Invalid changelog for {repo}')
        else:
            content = snapshot.read_text(encoding='utf-8')
        sources[product] = content
    for product, repo, output in PRODUCTS:
        content = sources[product]
        (ROOT / 'changelogs' / f'{product}.md').write_text(content, encoding='utf-8')
        (ROOT / output).write_text('// Generated by sync_changelog.py — do not edit.\n'
            + 'window.__FLINT_CHANGELOG_MD__ = ' + json.dumps(content, ensure_ascii=False) + ';\n', encoding='utf-8')


if __name__ == '__main__':
    main()
